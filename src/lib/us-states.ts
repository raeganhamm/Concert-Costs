const VALID_ABBRS = new Set(Object.keys(ABBR_TO_NAME));

export function normalizeStateToAbbr(input: string): string | null {
  const trimmed = input.trim();
  if (!trimmed) return null;

  const upper = trimmed.toUpperCase();
  if (upper.length === 2 && VALID_ABBRS.has(upper)) return upper;

  const fromName = STATE_NAME_TO_ABBR[trimmed.toLowerCase()];
  return fromName ?? null;
}

export function getVisitedStateAbbrs(concerts: Concert[]): Set<string> {
  const visited = new Set<string>();
  for (const concert of concerts) {
    const abbr = normalizeStateToAbbr(concert.state);
    if (abbr) visited.add(abbr);
  }
  return visited;
}

export function getConcertCountByState(concerts: Concert[]): Map<string, number> {
  const counts = new Map<string, number>();
  for (const concert of concerts) {
    const abbr = normalizeStateToAbbr(concert.state);
    if (!abbr) continue;
    counts.set(abbr, (counts.get(abbr) ?? 0) + 1);
  }
  return counts;
}

export function abbrFromFips(fips: string): string | undefined {
  return FIPS_TO_ABBR[fips];
}

export function fipsFromAbbr(abbr: string): string | undefined {
  return ABBR_TO_FIPS[abbr];
}
